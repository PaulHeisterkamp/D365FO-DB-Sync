using System.Text;

namespace DBSyncTool.Helpers
{
    /// <summary>
    /// Builds the T-SQL script behind the "Copy Truncate TSQL" button: it empties the transaction
    /// tables of the LOCAL AxDB so that, after a transaction-less copy, AxDB is consistent again
    /// (master data, setup and parameters from Tier2, no transactions).
    ///
    /// Table selection = the [TransactionLessExclude] lines (DefaultValues.ini + CustomValues.ini):
    ///  - "TableGroup:..." rules → resolved at run time in the target DB (SQLDICTIONARY + TABLEMETADATATABLE)
    ///  - exact names, and '*' wildcard patterns (→ LIKE)
    /// Per table it follows the original cleanup script: transaction, CDC disable/enable, TRUNCATE,
    /// TRY/CATCH - plus a batched DELETE fallback when TRUNCATE is not allowed (FK / schema-bound view).
    /// The script defaults to @Execute = 0, which only lists the tables and their row counts.
    /// Pure function so it can be generated and tested outside the UI.
    /// </summary>
    public static class TransactionTruncateSqlBuilder
    {
        public sealed class Result
        {
            public string Sql { get; init; } = string.Empty;
            public List<int> TableGroups { get; init; } = new();
            public List<string> Names { get; init; } = new();
            public List<string> Patterns { get; init; } = new();
        }

        public static Result Build(IEnumerable<string> excludeLines, DateTime generatedAt)
        {
            var groups = new SortedSet<int>();
            var names = new SortedSet<string>(StringComparer.OrdinalIgnoreCase);
            var patterns = new SortedSet<string>(StringComparer.OrdinalIgnoreCase);

            foreach (var raw in excludeLines)
            {
                var line = raw.Trim();
                if (line.Length == 0)
                    continue;

                if (TablePatternMatcher.IsTableGroupRule(line))
                    groups.UnionWith(TablePatternMatcher.ParseTableGroupRule(line));
                else if (line.Contains('*'))
                    patterns.Add(ToLikePattern(line));
                else
                    names.Add(line.ToUpperInvariant());
            }

            var groupNames = TablePatternMatcher.TableGroupValues
                .Where(kv => groups.Contains(kv.Value))
                .OrderBy(kv => kv.Value)
                .Select(kv => $"{kv.Key} ({kv.Value})");

            var sb = new StringBuilder();
            sb.AppendLine("/* =============================================================================");
            sb.AppendLine("   TRUNCATE TRANSACTION TABLES - transaction-less copy");
            sb.AppendLine($"   Generated by D365FO DB Sync Tool, {generatedAt:yyyy-MM-dd HH:mm}");
            sb.AppendLine();
            sb.AppendLine("   Run against the LOCAL AxDB (target) ONLY - never against Tier2 / production.");
            sb.AppendLine();
            sb.AppendLine("   A transaction-less copy refreshes master data, setup and parameters from Tier2 and");
            sb.AppendLine("   leaves the AxDB transactions untouched. This script removes those transactions, so");
            sb.AppendLine("   AxDB becomes consistent again: master data from Tier2, no transactions.");
            sb.AppendLine();
            sb.AppendLine("   Tables:");
            sb.AppendLine($"   - table groups: {(groups.Count > 0 ? string.Join(", ", groupNames) : "(none)")}");
            sb.AppendLine("     resolved in this database (SQLDICTIONARY + TABLEMETADATATABLE)");
            sb.AppendLine($"   - {names.Count} explicit table(s) and {patterns.Count} pattern(s) from [{TransactionLessHelper.ExcludeSection}]");
            sb.AppendLine("     in DefaultValues.ini and CustomValues.ini");
            sb.AppendLine("   Only dbo tables that exist and contain rows are processed.");
            sb.AppendLine();
            sb.AppendLine("   @Execute = 0 (default): only LISTS the tables with their row counts - nothing changes.");
            sb.AppendLine("   @Execute = 1           : truncates them. Take a backup / snapshot of AxDB first.");
            sb.AppendLine("   Per table: own transaction, CDC disabled/re-enabled if tracked, TRUNCATE TABLE;");
            sb.AppendLine("   if TRUNCATE is not allowed (foreign key / schema-bound view) DELETE in batches.");
            sb.AppendLine("   Errors are printed and the script continues with the next table.");
            sb.AppendLine("   ============================================================================= */");
            sb.AppendLine("SET NOCOUNT ON;");
            sb.AppendLine();
            sb.AppendLine("DECLARE @Execute BIT = 0;   -- set to 1 to truncate");
            sb.AppendLine();

            sb.AppendLine("DECLARE @Groups TABLE (TableGroup INT PRIMARY KEY);");
            if (groups.Count > 0)
                sb.AppendLine($"INSERT INTO @Groups (TableGroup) VALUES {string.Join(", ", groups.Select(g => $"({g})"))};");
            sb.AppendLine();

            sb.AppendLine("DECLARE @Names TABLE (Name SYSNAME PRIMARY KEY);");
            AppendValues(sb, "@Names (Name)", names);
            sb.AppendLine();

            sb.AppendLine("DECLARE @Patterns TABLE (Pattern NVARCHAR(256) PRIMARY KEY);");
            AppendValues(sb, "@Patterns (Pattern)", patterns);
            sb.AppendLine();

            sb.AppendLine(@"DECLARE @Tables TABLE (TableName SYSNAME PRIMARY KEY, Reason NVARCHAR(300), RowCnt BIGINT);

INSERT INTO @Tables (TableName, Reason)
SELECT x.TableName, MIN(x.Reason)
FROM (
    SELECT d.SQLNAME AS TableName, N'table group ' + CAST(m.TABLEGROUP AS NVARCHAR(10)) AS Reason
    FROM SQLDICTIONARY d
    INNER JOIN TABLEMETADATATABLE m ON m.TABLEID = d.TABLEID
    INNER JOIN @Groups g ON g.TableGroup = m.TABLEGROUP
    WHERE d.FIELDID = 0 AND d.ARRAY = 0
    UNION ALL
    SELECT n.Name, N'explicit' FROM @Names n
    UNION ALL
    SELECT t.name, N'pattern ' + p.Pattern
    FROM sys.tables t INNER JOIN @Patterns p ON t.name LIKE p.Pattern
    WHERE t.schema_id = SCHEMA_ID('dbo')
) x
WHERE EXISTS (SELECT 1 FROM sys.tables t WHERE t.name = x.TableName AND t.schema_id = SCHEMA_ID('dbo'))
GROUP BY x.TableName;

UPDATE tb SET RowCnt = ISNULL((SELECT SUM(ps.row_count) FROM sys.dm_db_partition_stats ps
                               WHERE ps.object_id = OBJECT_ID(N'dbo.' + QUOTENAME(tb.TableName)) AND ps.index_id IN (0, 1)), 0)
FROM @Tables tb;

DECLARE @TableCount INT, @TotalRows BIGINT, @EmptyCount INT;
SELECT @TableCount = COUNT(*), @TotalRows = ISNULL(SUM(RowCnt), 0), @EmptyCount = ISNULL(SUM(CASE WHEN RowCnt = 0 THEN 1 ELSE 0 END), 0) FROM @Tables;
PRINT CONCAT('Transaction tables found: ', @TableCount, ' (', @TableCount - @EmptyCount, ' with rows, ', @TotalRows, ' rows in total)');

IF @Execute = 0
BEGIN
    PRINT 'LIST ONLY (@Execute = 0) - nothing was changed. Set @Execute = 1 to truncate.';
    SELECT TableName, Reason, RowCnt FROM @Tables WHERE RowCnt > 0 ORDER BY RowCnt DESC, TableName;
    RETURN;
END

DECLARE @TableName SYSNAME, @SQL NVARCHAR(MAX), @ErrorMessage NVARCHAR(4000), @ErrorNumber INT, @CDCState BIT;
DECLARE @Done INT = 0, @Deleted INT = 0, @Failed INT = 0;

DECLARE TableCursor CURSOR LOCAL FAST_FORWARD FOR
    SELECT TableName FROM @Tables WHERE RowCnt > 0 ORDER BY TableName;
OPEN TableCursor;
FETCH NEXT FROM TableCursor INTO @TableName;
WHILE @@FETCH_STATUS = 0
BEGIN
    SET @CDCState = 0;
    BEGIN TRY
        BEGIN TRANSACTION;
        SELECT @CDCState = is_tracked_by_cdc FROM sys.tables WHERE name = @TableName AND schema_id = SCHEMA_ID('dbo');
        IF @CDCState = 1
        BEGIN
            SET @SQL = N'EXEC sys.sp_cdc_disable_table @source_schema = N''dbo'', @source_name = N''' + REPLACE(@TableName, '''', '''''') + N''', @capture_instance = N''dbo_' + REPLACE(@TableName, '''', '''''') + N'''';
            EXEC sp_executesql @SQL;
        END
        SET @SQL = N'TRUNCATE TABLE [dbo].' + QUOTENAME(@TableName);
        EXEC sp_executesql @SQL;
        IF @CDCState = 1
        BEGIN
            SET @SQL = N'EXEC sys.sp_cdc_enable_table @source_schema = N''dbo'', @source_name = N''' + REPLACE(@TableName, '''', '''''') + N''', @role_name = NULL';
            EXEC sp_executesql @SQL;
        END
        COMMIT TRANSACTION;
        SET @Done += 1;
        PRINT 'Truncated: ' + @TableName;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        SELECT @ErrorNumber = ERROR_NUMBER(), @ErrorMessage = ERROR_MESSAGE();
        IF @ErrorNumber IN (3729, 4712)   -- referenced by a schema-bound view / foreign key: TRUNCATE not allowed
        BEGIN
            BEGIN TRY
                SET @SQL = N'WHILE 1 = 1 BEGIN DELETE TOP (100000) FROM [dbo].' + QUOTENAME(@TableName) + N'; IF @@ROWCOUNT = 0 BREAK; END';
                EXEC sp_executesql @SQL;
                SET @Deleted += 1;
                PRINT 'Deleted (TRUNCATE not allowed): ' + @TableName;
            END TRY
            BEGIN CATCH
                SET @Failed += 1;
                PRINT 'Error deleting table ' + @TableName + '. Error: ' + ERROR_MESSAGE();
            END CATCH
        END
        ELSE
        BEGIN
            SET @Failed += 1;
            PRINT 'Error truncating table ' + @TableName + '. Error: ' + @ErrorMessage;
        END
    END CATCH
    FETCH NEXT FROM TableCursor INTO @TableName;
END
CLOSE TableCursor;
DEALLOCATE TableCursor;

PRINT CONCAT('Finished: ', @Done, ' truncated, ', @Deleted, ' deleted, ', @Failed, ' failed.');");

            return new Result
            {
                Sql = sb.ToString(),
                TableGroups = groups.ToList(),
                Names = names.ToList(),
                Patterns = patterns.ToList()
            };
        }

        /// <summary>'*' → '%'; LIKE meta characters in the name are escaped.</summary>
        private static string ToLikePattern(string pattern)
        {
            var sb = new StringBuilder();
            foreach (char c in pattern.ToUpperInvariant())
            {
                switch (c)
                {
                    case '*': sb.Append('%'); break;
                    case '%': sb.Append("[%]"); break;
                    case '_': sb.Append("[_]"); break;
                    case '[': sb.Append("[[]"); break;
                    default: sb.Append(c); break;
                }
            }
            return sb.ToString();
        }

        private static void AppendValues(StringBuilder sb, string target, IEnumerable<string> values)
        {
            var list = values.ToList();
            // INSERT ... VALUES allows at most 1000 rows per statement
            for (int i = 0; i < list.Count; i += 500)
            {
                var chunk = list.Skip(i).Take(500).Select(v => $"(N'{v.Replace("'", "''")}')");
                sb.AppendLine($"INSERT INTO {target} VALUES");
                sb.AppendLine("    " + string.Join(",\n    ", chunk) + ";");
            }
        }
    }
}
